'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),zlib=require('node:zlib');
const {normalizeStacks}=require('./native-stack-support.cjs');
test('native White Herb and Clear Body lifecycle contract reproduces pinned branches and witnesses',()=>{
 require('../reference/neutral-turn-oracle.cjs').assertReady();
 const spec=require('../reference/stat-drop-cases.cjs');
 const actual=JSON.parse(require('node:child_process').execFileSync('node',['reference/shared-engine-cases.cjs','--batch','statdrop'],{maxBuffer:16*1024*1024})),cases=actual.cases;
 assert.deepEqual(normalizeStacks(JSON.parse(JSON.stringify(actual))),normalizeStacks(JSON.parse(zlib.gunzipSync(fs.readFileSync('test-logs/g4-cpu-conformance/stat-drop.json.gz')))));
 assert.equal(cases.length,37);assert.equal(cases.reduce((n,c)=>n+c.steps.length,0),77);
 assert.ok(cases.every(c=>c.steps.every(s=>s.accepted.every(a=>a.accepted))));
 const mon=id=>cases.find(c=>c.id==='G4-stat-drop-'+id).steps[0].after.sides[1].pokemon[0];
 assert.equal(mon('clear-growl').boosts.atk,0);assert.equal(mon('clear-self').boosts.def,-1);
 assert.equal(mon('herb-self').boosts.def,0);assert.equal(mon('herb-self').boosts.atk,2);assert.equal(mon('herb-self').item,'');
 assert.equal(mon('herb-self').phaseState.lastItem,'whiteherb');assert.equal(mon('herb-self').phaseState.ateBerry,false);
 assert.equal(mon('herb-simple').boosts.atk,4);assert.equal(mon('herb-contrary').boosts.atk,0);assert.equal(mon('herb-contrary').boosts.def,1);
 const acquired=cases.find(c=>c.id==='G4-stat-drop-herb-acquire-negative').steps[1];
 assert.equal(acquired.after.sides[0].pokemon[0].item,'');assert.equal(acquired.after.sides[0].pokemon[0].boosts.def,0);
 assert.ok(cases.find(c=>c.id==='G4-stat-drop-herb-dual-idle').steps[0].draws.some(d=>d.semanticContext==='after-move'));
 assert.deepEqual(spec.membershipWitnesses().map(w=>w.set.species),['Klinklang','Crustle']);
});
