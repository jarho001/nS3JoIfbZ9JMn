'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),zlib=require('node:zlib');
const {normalizeStacks}=require('./native-stack-support.cjs');
test('native No Guard and Victory Star callback branches and membership reproduce',()=>{
 require('../reference/neutral-turn-oracle.cjs').assertReady();
 const spec=require('../reference/accuracy-ability-cases.cjs');
 const actual=JSON.parse(require('node:child_process').execFileSync('node',['reference/shared-engine-cases.cjs','--batch','accuracyability'],{maxBuffer:24*1024*1024}));
 assert.deepEqual(normalizeStacks(JSON.parse(JSON.stringify(actual))),normalizeStacks(JSON.parse(zlib.gunzipSync(fs.readFileSync('test-logs/g4-cpu-conformance/accuracy-ability.json.gz')))));
 assert.equal(actual.cases.length,48);assert.equal(actual.cases.reduce((n,c)=>n+c.steps.length,0),70);
 assert.ok(actual.cases.every(c=>c.steps.every(s=>s.accepted.every(a=>a.accepted))));
 const c=id=>actual.cases.find(c=>c.id==='G4-accuracy-ability-'+id),draws=id=>c(id).steps[0].draws;
 assert.ok(!draws('noguard-source-megapunch').some(d=>d.semanticContext==='accuracy'));
 assert.ok(!draws('noguard-target-megapunch').some(d=>d.semanticContext==='accuracy'));
 assert.ok(draws('victorystar-source-megapunch').some(d=>d.semanticContext==='accuracy'));
 assert.ok(c('noguard-ghost').steps[0].events.p1.some(e=>e.message.startsWith('|-immune|')));
 assert.ok(draws('noguard-dual-tie').some(d=>d.semanticContext==='accuracy-sort'));
 assert.ok(draws('victorystar-dual-tie').some(d=>d.semanticContext==='modify-accuracy-sort'));
 assert.ok(c('control-threshold').steps[0].events.p1.some(e=>e.message.startsWith('|-miss|')));
 assert.ok(!c('victorystar-threshold').steps[0].events.p1.some(e=>e.message.startsWith('|-miss|')));
 assert.deepEqual(spec.membershipWitnesses().map(w=>w.set.species),['Golurk','Victini']);
});
